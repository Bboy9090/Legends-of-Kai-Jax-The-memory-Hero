/**
 * Generate full name
 */
export function getFullBronxName(id: string): string {
  const name = BRONX_MYTHICAL_NAMES[id];
  if (!name) return id;
  return `${name.first} ${name.last}`;
}

/**
 * Get name with title
 */
export function getNameWithTitle(id: string): string {
  const name = BRONX_MYTHICAL_NAMES[id];
  if (!name) return id;
  return `${name.first} ${name.last}, ${name.title}`;
}
