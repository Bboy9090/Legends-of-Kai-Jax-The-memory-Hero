/**
 * Get all beasts
 */
export function getAllBeasts(): LegendaryBeast[] {
  return COMPLETE_BEAST_ROSTER;
}

/**
 * Get beast by ID
 */
export function getBeastById(id: string): LegendaryBeast | undefined {
  return COMPLETE_BEAST_ROSTER.find(beast => beast.id === id);
}

/**
 * Get beasts by role
 */
export function getBeastsByRole(role: LegendaryBeast['role']): LegendaryBeast[] {
  return COMPLETE_BEAST_ROSTER.filter(beast => beast.role === role);
}
